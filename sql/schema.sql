BEGIN;
CREATE SCHEMA IF NOT EXISTS storebot;
REVOKE ALL ON SCHEMA storebot FROM PUBLIC, anon, authenticated;
SET LOCAL search_path TO storebot, pg_catalog;

            
            CREATE TABLE IF NOT EXISTS settings (
                guild_id BIGINT PRIMARY KEY, staff_role_id BIGINT, log_channel_id BIGINT
            );
            CREATE TABLE IF NOT EXISTS products (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, guild_id BIGINT NOT NULL, sku TEXT NOT NULL,
                name TEXT NOT NULL, description TEXT NOT NULL, price BIGINT NOT NULL CHECK(price>0),
                stock BIGINT NOT NULL CHECK(stock>=0), active BIGINT NOT NULL DEFAULT 1,
                UNIQUE(guild_id,sku)
            );
            CREATE TABLE IF NOT EXISTS orders (
                code BIGINT PRIMARY KEY, guild_id BIGINT NOT NULL, buyer_id BIGINT NOT NULL,
                product_id BIGINT NOT NULL REFERENCES products(id), name TEXT NOT NULL,
                unit_price BIGINT NOT NULL, quantity BIGINT NOT NULL, total BIGINT NOT NULL,
                status TEXT NOT NULL DEFAULT 'pending', provider TEXT NOT NULL,
                reserved BIGINT NOT NULL DEFAULT 1, created_at BIGINT NOT NULL,
                expires_at BIGINT NOT NULL, link_id TEXT UNIQUE, checkout_url TEXT,
                qr_code TEXT, description TEXT, account_number TEXT, account_name TEXT,
                paid_at BIGINT, review_reason TEXT, checked_at BIGINT NOT NULL DEFAULT 0
            );
            CREATE INDEX IF NOT EXISTS orders_buyer_pending ON orders(guild_id,buyer_id,status);
            CREATE INDEX IF NOT EXISTS orders_reconcile ON orders(provider,status,checked_at);
            CREATE INDEX IF NOT EXISTS orders_guild ON orders(guild_id,created_at);
            CREATE TABLE IF NOT EXISTS payment_events (
                reference TEXT PRIMARY KEY, order_code BIGINT NOT NULL,
                amount BIGINT NOT NULL, created_at BIGINT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS audit (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, guild_id BIGINT NOT NULL, actor_id BIGINT,
                action TEXT NOT NULL, detail TEXT NOT NULL, created_at BIGINT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS outbox (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_code BIGINT NOT NULL REFERENCES orders(code),
                status TEXT NOT NULL, delivered BIGINT NOT NULL DEFAULT 0,
                attempts BIGINT NOT NULL DEFAULT 0, retry_at BIGINT NOT NULL DEFAULT 0,
                UNIQUE(order_code,status)
            );
            
CREATE INDEX IF NOT EXISTS events_order ON payment_events(order_code);
CREATE UNIQUE INDEX IF NOT EXISTS manual_transfer_code ON orders(description)
    WHERE provider='manual' AND description IS NOT NULL;

ALTER TABLE storebot.settings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON storebot.settings FROM PUBLIC, anon, authenticated;

ALTER TABLE storebot.products ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON storebot.products FROM PUBLIC, anon, authenticated;

ALTER TABLE storebot.orders ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON storebot.orders FROM PUBLIC, anon, authenticated;

ALTER TABLE storebot.payment_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON storebot.payment_events FROM PUBLIC, anon, authenticated;

ALTER TABLE storebot.audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON storebot.audit FROM PUBLIC, anon, authenticated;

ALTER TABLE storebot.outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON storebot.outbox FROM PUBLIC, anon, authenticated;

REVOKE ALL ON ALL SEQUENCES IN SCHEMA storebot FROM PUBLIC, anon, authenticated;
CREATE TABLE IF NOT EXISTS storebot.ticket_settings (
    guild_id BIGINT PRIMARY KEY,
    category_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS storebot.tickets (
    order_code BIGINT PRIMARY KEY REFERENCES storebot.orders(code),
    guild_id BIGINT NOT NULL,
    buyer_id BIGINT NOT NULL,
    channel_id BIGINT NOT NULL UNIQUE,
    closed BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL
);
ALTER TABLE storebot.ticket_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE storebot.tickets ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON storebot.ticket_settings, storebot.tickets FROM PUBLIC, anon, authenticated;

COMMIT;
